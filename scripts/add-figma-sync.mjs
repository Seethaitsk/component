const filePath = path.join(process.cwd(), 'src', 'data', 'components.js');
let content = fs.readFileSync(filePath, 'utf8');

// For each component, inject the figma object if not already present
for (const [id, figmaData] of Object.entries(figmaSpecsMap)) {
  const idRegex = new RegExp(`(id:\\s*'${id}',[\\s\\S]*?)(code:\\s*\\{)`);
  if (idRegex.test(content) && !content.includes(`nodeId: '${figmaData.nodeId}'`)) {
    const figmaStr = `    figma: ${JSON.stringify(figmaData, null, 6).replace(/\n/g, '\n    ')},\n    `;
    content = content.replace(idRegex, `$1${figmaStr}$2`);
    console.log(`Injected Figma specs for ${id}`);
  }
}

fs.writeFileSync(filePath, content, 'utf8');
console.log('Successfully updated src/data/components.js with Figma sync specifications!');
